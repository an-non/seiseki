export function buildDemoExplainerRecords() {
  return Array.from({ length: 100 }, (_, index) => {
    const [theme, priority, baseText] = themes[index % themes.length];
    const econ = index % 5 + 1;
    const social = index * 2 % 5 + 1;
    const support = supports[index % supports.length];
    return Object.freeze({
      key: `${DEMO_EXPLAINER_BATCH_ID}-${String(index + 1).padStart(3, "0")}`,
      appVersion: `デモデータ100-v1-${String(index + 1).padStart(3, "0")}`,
      scenario: `${theme} / 経済${econ} / 社会${social} / ${support}`,
      demo: Object.freeze({
        age: ages[index % ages.length],
        gender: genders[index * 3 % genders.length],
        region: regions[index * 4 % regions.length],
        occupation: occupations[index * 5 % occupations.length],
        party: parties[index * 7 % parties.length]
      }),
      answers: Object.freeze({
        q_support: support,
        q_priority: priority,
        q_econ: String(econ),
        q_information: information[index * 3 % information.length],
        q_social: String(social),
        q_life: life[index * 4 % life.length],
        q_participation: participation[index * 2 % participation.length]
      }),
      freeText: `${baseText} ${econText[econ]} ${socialText[social]} ${supportText[support]} ${variants[Math.floor(index / 10)]}`
    });
  });
}

export const DEMO_EXPLAINER_RECORDS = Object.freeze(buildDemoExplainerRecords());
